"""Verify that the registry-form lockfile copy re-sources only the recorded path packages."""

from pathlib import Path
import runpy
import tomllib
import unittest


ADVISORIES = runpy.run_path(str(Path(__file__).with_name("advisories.py")))
REGISTRY = ADVISORIES["REGISTRY"]
REGISTRY_FORM = ADVISORIES["registry_form"]

LOCKFILE = """# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 4

[[package]]
name = "bytes"
version = "1.10.1"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "d71b6127be86fdcfddb610f7182ac57211d4b18a3e9c82eb2d17662f2227ad6a"

[[package]]
name = "quinn-proto"
version = "0.11.18"
dependencies = [
 "bytes",
]

[[package]]
name = "tn-node"
version = "0.1.0"
dependencies = [
 "quinn-proto",
]
"""


class RegistryForm(unittest.TestCase):
    def test_recorded_path_package_gains_the_registry_source_and_nothing_else_changes(self):
        copy, rewritten = REGISTRY_FORM(LOCKFILE, {("quinn-proto", "0.11.18")})
        self.assertEqual(rewritten, [{"name": "quinn-proto", "version": "0.11.18"}])
        packages = {package["name"]: package for package in tomllib.loads(copy)["package"]}
        self.assertEqual(packages["quinn-proto"]["source"], REGISTRY)
        self.assertEqual(packages["quinn-proto"]["dependencies"], ["bytes"])
        self.assertNotIn("source", packages["tn-node"])
        inserted = f'version = "0.11.18"\nsource = "{REGISTRY}"\n'
        self.assertEqual(copy.replace(inserted, 'version = "0.11.18"\n', 1), LOCKFILE)

    def test_registry_packages_and_absent_identities_are_refused(self):
        registry = LOCKFILE.replace('version = "0.11.18"\n', f'version = "0.11.18"\nsource = "{REGISTRY}"\n', 1)
        for lockfile, identities in ((registry, {("quinn-proto", "0.11.18")}),
                                     (LOCKFILE, {("quinn-proto", "0.11.6")}),
                                     (LOCKFILE, {("quinn-proto", "0.11.18"), ("libp2p-quic", "0.14.0")})):
            with self.subTest(identities=sorted(identities)):
                with self.assertRaises(RuntimeError):
                    REGISTRY_FORM(lockfile, identities)
        self.assertEqual(REGISTRY_FORM(LOCKFILE, set()), (LOCKFILE, []))


if __name__ == "__main__":
    unittest.main()
